function initialLang() {
  try {
    const saved = localStorage.getItem('crm.lang')
    if (saved === 'ro' || saved === 'ru' || saved === 'en') return saved
  } catch {
    /* ignorat */
  }
  return navigator.language?.startsWith('ru') ? 'ru' : navigator.language?.startsWith('en') ? 'en' : 'ro'
}

type Tree = Record<string, unknown>
function merge(...parts: Tree[]): Tree {
  const out: Tree = {}
  for (const part of parts) {
    for (const [k, v] of Object.entries(part)) {
      out[k] = v && typeof v === 'object' && !Array.isArray(v) && out[k] && typeof out[k] === 'object'
        ? merge(out[k] as Tree, v as Tree) : v
    }
  }
  return out
}

